#!/usr/bin/env python3
"""
Generate the BASE / ADD tables for chall.c from a flag string.

The point is to break `strings`: the flag is never stored as a
contiguous printable run in the binary.  Each flag byte is recovered
at runtime as `(BASE[i] + ADD[i]) & 0xff`.

The split is done with a fixed random key (printed at the top of the
output) so two different runs of the script on the same flag produce
the same tables — that keeps the build reproducible.  Override the key
with `--key 0x...` if you want to rotate.
"""

from __future__ import annotations

import argparse
import secrets
import sys


def split_byte(b: int, key_byte: int) -> tuple[int, int]:
    """Split a byte `b` into two bytes `a, d` such that (a + d) & 0xff == b.

    To keep the BASE/ADD arrays non-trivial we want neither array to
    be printable ASCII on its own.  We pick `a` randomly in
    0x10..0xBF, and derive `d` from the flag byte and the key.
    """
    a = key_byte
    d = (b - a) & 0xff
    return a, d


def gen_tables(flag: str, key: bytes) -> tuple[list[int], list[int]]:
    raw = flag.encode("latin-1")
    if len(key) < len(raw):
        raise ValueError("key must be at least as long as the flag")
    base = []
    add = []
    for b, k in zip(raw, key):
        a, d = split_byte(b, k)
        base.append(a)
        add.append(d)
    return base, add


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--flag", required=True, help="the flag string, e.g. nmctf{...}")
    ap.add_argument(
        "--key",
        default=None,
        help="hex-encoded key bytes (auto-generated if not given)",
    )
    ap.add_argument("--print-key", action="store_true", help="echo the key on stdout")
    args = ap.parse_args()

    if args.key is None:
        key = secrets.token_bytes(len(args.flag))
        if args.print_key:
            print(f"[*] generated key: {key.hex()}", file=sys.stderr)
    else:
        key = bytes.fromhex(args.key)

    base, add = gen_tables(args.flag, key)

    def fmt(arr: list[int]) -> str:
        rows = []
        for i in range(0, len(arr), 8):
            row = ", ".join(f"0x{b:02x}" for b in arr[i : i + 8])
            rows.append("    " + row + ",")
        return "\n".join(rows)

    print("/* Auto-generated by tools/gen_flag.py -- do not edit by hand. */")
    print(f"/* flag = {args.flag!r}  */")
    print(f"/* key  = {key.hex()}  */")
    print(f"static const unsigned char BASE[] = {{\n{fmt(base)}\n}};")
    print(f"static const unsigned char ADD[]  = {{\n{fmt(add)}\n}};")

    # Sanity: re-decode and compare.
    decoded = bytes((b + a) & 0xff for b, a in zip(base, add)).decode("latin-1")
    if decoded != args.flag:
        print(f"[!] sanity check failed: got {decoded!r}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
